#include <unistd.h>

void	ft_putnbr(int nb)
{
	int	a;
	int	ans;

	a = 0;
	if (nb == -2147483648)
	{
		write(1, "-2147483648", 11);
		return ;
	}
	else if (nb < 0)
	{
		write(1, "-", 1);
		nb *= -1;
	}
	if (nb >= 10)
	{
		ft_putnbr(nb / 10);
	}
	ans = nb % 10 + '0';
	write(1, &ans, 1);
}
int main()
{
	ft_putnbr(214748364);
}
