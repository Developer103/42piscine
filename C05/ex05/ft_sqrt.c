#include <stdio.h>

int	ft_sqrt(int nb)
{
	int	a;

	a = 1;
	if (nb == 0)
		return (0);
	if (nb == 1)
		return (1);
	while (a <= nb / a)
	{
		if (a * a == nb)
			return (a);
		a++;
	}
	return (0);
}
